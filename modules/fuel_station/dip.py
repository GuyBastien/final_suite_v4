# This file is part of the Tryton fuel_station module.
from trytond.i18n import gettext
from trytond.model import ModelSQL, ModelView, Workflow, fields
from trytond.pool import Pool
from trytond.pyson import Bool, Eval, If
from trytond.transaction import Transaction, without_check_access

from .exceptions import DipError, FuelWarning
from .tools import volume_correction_factor


class Dip(Workflow, ModelSQL, ModelView):
    "Tank Dip"
    __name__ = 'fuel.dip'
    _rec_name = 'number'

    number = fields.Char("Number", readonly=True,
        help="Number assigned automatically by the sequence.")
    company = fields.Many2One(
        'company.company', "Company", required=True,
        states={'readonly': Eval('state') != 'draft'},
        help="Company that owns the record.")
    station = fields.Many2One(
        'fuel.station', "Station", required=True,
        domain=[('company', '=', Eval('company', -1))],
        states={'readonly': Eval('state') != 'draft'},
        help="Station concerned.")
    tank = fields.Many2One(
        'fuel.tank', "Tank", required=True,
        domain=[('station', '=', Eval('station', -1))],
        states={'readonly': Eval('state') != 'draft'},
        help="Tank concerned.")
    date = fields.Date(
        "Date", required=True,
        states={'readonly': Eval('state') != 'draft'},
        help="Date of the document.")
    unit = fields.Function(
        fields.Many2One('product.uom', "Unit",
        help="Unit of measure."), 'on_change_with_unit')
    measured_quantity = fields.Float(
        "Measured Quantity", digits='unit', required=True,
        domain=[('measured_quantity', '>=', 0)],
        states={'readonly': Eval('state') != 'draft'},
        help="Quantity read with the dip stick or the probe.")
    temperature = fields.Float(
        "Temperature (°C)", digits=(16, 1),
        states={'readonly': Eval('state') != 'draft'},
        help="Temperature of the fuel. With the station option "
        "\"Book at 15 °C\" the measured quantity is corrected to 15 °C.")
    net_quantity = fields.Function(
        fields.Float("Quantity at 15 °C", digits='unit',
        help="Volume converted to the reference temperature of 15 °C."),
        'on_change_with_net_quantity')
    book_quantity = fields.Float(
        "Book Quantity", digits='unit', readonly=True,
        help="Quantity given by the stock when the dip is validated.")
    variance = fields.Float(
        "Variance", digits='unit', readonly=True,
        help="Measured minus book quantity: negative = loss.")
    variance_percent = fields.Function(
        fields.Float("Variance (%)", digits=(16, 2),
        help="Gap between expected and measured volume, in percent."),
        'get_variance_percent')
    adjust = fields.Boolean(
        "Adjust Stock",
        states={'readonly': Eval('state') != 'draft'},
        help="Create the stock move that aligns the book stock on the "
        "measured quantity.")
    move = fields.Many2One('stock.move', "Stock Move", readonly=True,
        help="Stock move generated by this record.")
    notes = fields.Text("Notes",
        help="Free text for internal use.")
    state = fields.Selection([
            ('draft', "Draft"),
            ('done', "Done"),
            ('cancelled', "Cancelled"),
            ], "State", readonly=True, required=True,
        help="Current step of the workflow.")

    @classmethod
    def __setup__(cls):
        super().__setup__()
        cls._order.insert(0, ('date', 'DESC'))
        cls._order.insert(1, ('id', 'DESC'))
        cls._transitions |= {
            ('draft', 'done'),
            ('draft', 'cancelled'),
            ('cancelled', 'draft'),
            }
        cls._buttons.update({
                'cancel': {
                    'invisible': Eval('state') != 'draft',
                    'depends': ['state']},
                'draft': {
                    'invisible': Eval('state') != 'cancelled',
                    'depends': ['state']},
                'validate_dip': {
                    'invisible': Eval('state') != 'draft',
                    'depends': ['state']},
                })

    @classmethod
    def view_attributes(cls):
        return super().view_attributes() + [
            ('/tree', 'visual', If(
                    Eval('state') == 'cancelled', 'muted',
                    If(Eval('state') == 'open', 'warning',
                        If(Eval('state') == 'done', 'success', '')))),
            ]

    def get_variance_percent(self, name):
        if self.book_quantity:
            return round(self.variance / self.book_quantity * 100, 4)
        return 0.

    @classmethod
    def default_company(cls):
        return Transaction().context.get('company')

    @classmethod
    def default_date(cls):
        return Pool().get('ir.date').today()

    @classmethod
    def default_state(cls):
        return 'draft'

    @classmethod
    def default_adjust(cls):
        return False

    @fields.depends('tank')
    def on_change_with_unit(self, name=None):
        if self.tank:
            return self.tank.product.default_uom.id

    @fields.depends('tank', 'measured_quantity', 'temperature')
    def on_change_with_net_quantity(self, name=None):
        if not self.tank:
            return self.measured_quantity or 0.
        template = self.tank.product.template
        factor = volume_correction_factor(
            template.fuel_family, template.fuel_density, self.temperature)
        return round((self.measured_quantity or 0.) * factor, 3)

    def accounted_quantity(self):
        "Measured quantity used for the comparison with the stock"
        if self.station.temperature_correction:
            return self.on_change_with_net_quantity()
        return self.measured_quantity

    @fields.depends('tank', 'station')
    def on_change_tank(self):
        if self.tank:
            self.station = self.tank.station

    @classmethod
    def create(cls, vlist):
        pool = Pool()
        Sequence = pool.get('ir.sequence')
        ModelData = pool.get('ir.model.data')
        vlist = [v.copy() for v in vlist]
        sequence = Sequence(ModelData.get_id('fuel_station', 'sequence_dip'))
        for values in vlist:
            if not values.get('number'):
                values['number'] = sequence.get()
        return super().create(vlist)

    @classmethod
    def copy(cls, dips, default=None):
        default = {} if default is None else default.copy()
        for name in ('number', 'move', 'book_quantity', 'variance'):
            default.setdefault(name, None)
        return super().copy(dips, default=default)

    @classmethod
    def delete(cls, dips):
        for dip in dips:
            if dip.state == 'done':
                raise DipError(gettext(
                        'fuel_station.msg_dip_delete_done', dip=dip.rec_name))
        super().delete(dips)

    @classmethod
    def validate(cls, dips):
        super().validate(dips)
        for dip in dips:
            if dip.tank.station != dip.station:
                raise DipError(gettext(
                        'fuel_station.msg_dip_tank_station',
                        tank=dip.tank.rec_name))

    @classmethod
    @ModelView.button
    @Workflow.transition('cancelled')
    def cancel(cls, dips):
        pass

    @classmethod
    @ModelView.button
    @Workflow.transition('draft')
    def draft(cls, dips):
        pass

    @classmethod
    @ModelView.button
    @Workflow.transition('done')
    def validate_dip(cls, dips):
        pool = Pool()
        Tank = pool.get('fuel.tank')
        Move = pool.get('stock.move')
        Warning = pool.get('res.user.warning')
        moves = []
        for dip in dips:
            book = Tank.quantities([dip.tank]).get(dip.tank.id, 0.)
            variance = round(dip.accounted_quantity() - book, 3)
            tolerance = dip.station.dip_tolerance / 100. * max(book, 0.)
            if abs(variance) > tolerance + 1e-6:
                key = 'fuel_dip_variance_%s' % dip.id
                if Warning.check(key):
                    raise FuelWarning(key, gettext(
                            'fuel_station.msg_dip_variance',
                            tank=dip.tank.rec_name, variance=variance,
                            book=book))
            values = {'book_quantity': book, 'variance': variance}
            if dip.adjust and abs(variance) > 1e-6:
                move = dip.get_move(variance)
                moves.append((dip, move))
            cls.write([dip], values)
        if moves:
            with without_check_access():
                Move.save([m for _, m in moves])
                Move.do([m for _, m in moves])
            for dip, move in moves:
                cls.write([dip], {'move': move.id})

    def get_move(self, variance):
        pool = Pool()
        Move = pool.get('stock.move')
        Location = pool.get('stock.location')
        locations = Location.search([('type', '=', 'lost_found')], limit=1)
        if not locations:
            raise DipError(gettext('fuel_station.msg_dip_no_lost_found'))
        lost_found = locations[0]
        product = self.tank.product
        move = Move()
        move.company = self.company
        move.currency = self.company.currency
        move.product = product
        move.unit = product.default_uom
        move.quantity = abs(variance)
        if variance > 0:
            move.from_location, move.to_location = (
                lost_found, self.tank.location)
        else:
            move.from_location, move.to_location = (
                self.tank.location, lost_found)
        move.effective_date = self.date
        move.unit_price = product.cost_price
        move.origin = self
        return move
