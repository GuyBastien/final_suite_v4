from decimal import Decimal

from trytond.i18n import gettext
from trytond.model import ModelSQL, ModelView, fields
from trytond.modules.product import price_digits
from trytond.pool import Pool
from trytond.pyson import Bool, Eval

from .exceptions import ShiftError

_ZERO = Decimal(0)


class ShiftSale(ModelSQL, ModelView):
    "Fuel Shift Shop Sale"
    __name__ = 'fuel.shift.sale'

    shift = fields.Many2One(
        'fuel.shift', "Shift", required=True, ondelete='CASCADE',
        help="Shift concerned.")
    product = fields.Many2One(
        'product.product', "Product", required=True,
        domain=[('template.fuel', '=', False),
            ('template.type', '=', 'goods')],
        states={'readonly': Bool(Eval('move'))},
        help="Shop article, lubricant, LPG cylinder, etc.")
    unit = fields.Function(
        fields.Many2One('product.uom', "Unit",
        help="Unit of measure."), 'on_change_with_unit')
    currency = fields.Function(
        fields.Many2One('currency.currency', "Currency",
        help="Currency of the amounts."),
        'on_change_with_currency')
    quantity = fields.Float(
        "Quantity", digits='unit', required=True,
        domain=[('quantity', '>', 0)],
        states={'readonly': Bool(Eval('move'))},
        help="Quantity, in the unit of measure.")
    unit_price = fields.Numeric(
        "Unit Price", digits=price_digits, required=True,
        domain=[('unit_price', '>=', 0)],
        states={'readonly': Bool(Eval('move'))},
        help="Price of one unit before discount.")
    amount = fields.Function(
        fields.Numeric("Amount", digits='currency',
        help="Amount in the currency of the document."),
        'on_change_with_amount')
    move = fields.Many2One('stock.move', "Stock Move", readonly=True,
        help="Stock move generated by this record.")

    @classmethod
    def __setup__(cls):
        super().__setup__()
        cls._order.insert(0, ('shift', 'ASC'))
        cls._order.insert(1, ('id', 'ASC'))

    @classmethod
    def default_quantity(cls):
        return 1.

    @fields.depends('product')
    def on_change_with_unit(self, name=None):
        if self.product:
            return self.product.default_uom.id

    @fields.depends('shift', '_parent_shift.currency')
    def on_change_with_currency(self, name=None):
        if self.shift and self.shift.currency:
            return self.shift.currency.id

    @fields.depends('product', 'unit_price')
    def on_change_product(self):
        if self.product:
            self.unit_price = self.product.list_price_used

    @fields.depends('quantity', 'unit_price', 'shift', '_parent_shift.currency')
    def on_change_with_amount(self, name=None):
        if self.unit_price is None or not self.quantity:
            return _ZERO
        amount = Decimal(str(round(self.quantity, 6))) * self.unit_price
        currency = self.shift.currency if self.shift else None
        return currency.round(amount) if currency else amount

    @classmethod
    def create(cls, vlist):
        cls._check_open(vlist=vlist)
        return super().create(vlist)

    @classmethod
    def write(cls, *args):
        actions = iter(args)
        for sales, _ in zip(actions, actions):
            cls._check_open(sales=sales)
        super().write(*args)

    @classmethod
    def delete(cls, sales):
        cls._check_open(sales=sales)
        super().delete(sales)

    @classmethod
    def _check_open(cls, sales=(), vlist=()):
        Shift = Pool().get('fuel.shift')
        shifts = [s.shift for s in sales]
        shifts += [Shift(v['shift']) for v in vlist if v.get('shift')]
        for shift in shifts:
            if shift.state in {'closed', 'cancelled'}:
                raise ShiftError(gettext(
                        'fuel_station.msg_payment_shift_closed',
                        shift=shift.rec_name))

    def get_move(self, to_location):
        Move = Pool().get('stock.move')
        shift = self.shift
        move = Move()
        move.company = shift.company
        move.currency = shift.company.currency
        move.product = self.product
        move.unit = self.product.default_uom
        move.quantity = self.quantity
        move.from_location = shift.station.warehouse.storage_location
        move.to_location = to_location
        move.effective_date = shift.date
        move.unit_price = self.unit_price
        move.origin = self
        return move
